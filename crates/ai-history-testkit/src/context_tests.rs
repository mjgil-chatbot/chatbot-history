//! Context crate design tests
//!
//! Task 14: Complete `ai-history-context` crate design
//!
//! Verify:
//! - ContextSnapshot exists with required fields
//! - SelectedFileRef, RetrievedChunkRef, ToolOutputRef exist
//! - SummaryRef, MemoryRef, RuleRef exist
//! - ModelConfig exists
//! - ReproducibilityInfo exists

#[cfg(test)]
mod test_context_snapshot {
    use ai_history_context::{ContextSnapshot, RetrievedChunkRef, SelectedFileRef, ToolOutputRef};
    use ai_history_core::{ContentHash, TurnId};

    /// Verify ContextSnapshot exists
    #[test]
    fn test_context_snapshot_exists() {
        let turn_id = TurnId::new();
        let snapshot = ContextSnapshot::new(turn_id);
        assert!(snapshot.selected_files.is_empty());
        assert!(snapshot.retrieved_chunks.is_empty());
        assert!(snapshot.tool_outputs.is_empty());
    }

    /// Verify SelectedFileRef exists
    #[test]
    fn test_selected_file_ref_exists() {
        let ref_ = SelectedFileRef {
            path: "src/main.rs".to_string(),
            blob_hash: ContentHash::new(b"content"),
            line_range: None,
            relevance_score: Some(0.9),
        };
        assert_eq!(ref_.path, "src/main.rs");
    }

    /// Verify RetrievedChunkRef exists
    #[test]
    fn test_retrieved_chunk_ref_exists() {
        let ref_ = RetrievedChunkRef {
            chunk_id: "chunk_1".to_string(),
            source: "src/main.rs".to_string(),
            blob_hash: ContentHash::new(b"content"),
            relevance_score: 0.8,
        };
        assert_eq!(ref_.chunk_id, "chunk_1");
    }

    /// Verify ToolOutputRef exists
    #[test]
    fn test_tool_output_ref_exists() {
        let ref_ = ToolOutputRef {
            tool_call_id: "call_1".to_string(),
            tool_name: "bash".to_string(),
            output_hash: ContentHash::new(b"output"),
            timestamp: ai_history_core::Timestamp::now(),
        };
        assert_eq!(ref_.tool_call_id, "call_1");
    }
}

#[cfg(test)]
mod test_context_references {
    use ai_history_context::{MemoryRef, MemoryType, RuleRef, SummaryRef, SummaryType};
    use ai_history_core::ContentHash;

    /// Verify SummaryRef exists
    #[test]
    fn test_summary_ref_exists() {
        let ref_ = SummaryRef {
            summary_id: "summary_1".to_string(),
            summary_hash: ContentHash::new(b"summary"),
            summary_type: SummaryType::AutoGenerated,
        };
        assert!(matches!(ref_.summary_type, SummaryType::AutoGenerated));
    }

    /// Verify MemoryRef exists
    #[test]
    fn test_memory_ref_exists() {
        let ref_ = MemoryRef {
            memory_id: "mem_1".to_string(),
            memory_hash: ContentHash::new(b"memory"),
            memory_type: MemoryType::LongTerm,
        };
        assert!(matches!(ref_.memory_type, MemoryType::LongTerm));
    }

    /// Verify RuleRef exists
    #[test]
    fn test_rule_ref_exists() {
        let ref_ = RuleRef {
            rule_set_id: "rule_1".to_string(),
            rules_hash: ContentHash::new(b"rule"),
        };
        assert_eq!(ref_.rule_set_id, "rule_1");
    }

    /// Verify SummaryType variants
    #[test]
    fn test_summary_type_variants() {
        assert!(matches!(
            SummaryType::AutoGenerated,
            SummaryType::AutoGenerated
        ));
        assert!(matches!(
            SummaryType::UserProvided,
            SummaryType::UserProvided
        ));
        assert!(matches!(
            SummaryType::SystemProvided,
            SummaryType::SystemProvided
        ));
    }

    /// Verify MemoryType variants
    #[test]
    fn test_memory_type_variants() {
        assert!(matches!(MemoryType::LongTerm, MemoryType::LongTerm));
        assert!(matches!(MemoryType::ShortTerm, MemoryType::ShortTerm));
        assert!(matches!(MemoryType::Ephemeral, MemoryType::Ephemeral));
    }
}

