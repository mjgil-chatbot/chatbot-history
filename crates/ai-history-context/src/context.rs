//! Context snapshot for turn reproducibility

use ai_history_core::{ContentHash, TurnId};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

/// Context snapshot capturing the state at turn creation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ContextSnapshot {
    pub turn_id: TurnId,
    pub selected_files: Vec<SelectedFileRef>,
    pub retrieved_chunks: Vec<RetrievedChunkRef>,
    pub tool_outputs: Vec<ToolOutputRef>,
    pub summary_refs: Vec<SummaryRef>,
    pub memory_refs: Vec<MemoryRef>,
    pub rule_refs: Vec<RuleRef>,
    pub system_prompt_hash: ContentHash,
    pub model_config: ModelConfig,
}

impl ContextSnapshot {
    pub fn new(turn_id: TurnId) -> Self {
        Self {
            turn_id,
            selected_files: Vec::new(),
            retrieved_chunks: Vec::new(),
            tool_outputs: Vec::new(),
            summary_refs: Vec::new(),
            memory_refs: Vec::new(),
            rule_refs: Vec::new(),
            system_prompt_hash: ContentHash::default(),
            model_config: ModelConfig::default(),
        }
    }

    pub fn add_selected_file(&mut self, file: SelectedFileRef) {
        self.selected_files.push(file);
    }

    pub fn add_retrieved_chunk(&mut self, chunk: RetrievedChunkRef) {
        self.retrieved_chunks.push(chunk);
    }

    pub fn add_tool_output(&mut self, output: ToolOutputRef) {
        self.tool_outputs.push(output);
    }

    pub fn total_references(&self) -> usize {
        self.selected_files.len()
            + self.retrieved_chunks.len()
            + self.tool_outputs.len()
            + self.summary_refs.len()
            + self.memory_refs.len()
            + self.rule_refs.len()
    }
}

/// Reference to a selected file
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SelectedFileRef {
    pub path: String,
    pub blob_hash: ContentHash,
    pub line_range: Option<LineRange>,
    pub relevance_score: Option<f32>,
}

/// Line range in a file
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LineRange {
    pub start: u32,
    pub end: u32,
}

/// Reference to a retrieved context chunk
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RetrievedChunkRef {
    pub chunk_id: String,
    pub source: String,
    pub blob_hash: ContentHash,
    pub relevance_score: f32,
}

/// Reference to a tool's output
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ToolOutputRef {
    pub tool_call_id: String,
    pub tool_name: String,
    pub output_hash: ContentHash,
    pub timestamp: ai_history_core::Timestamp,
}

/// Reference to a summary
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SummaryRef {
    pub summary_id: String,
    pub summary_hash: ContentHash,
    pub summary_type: SummaryType,
}

/// Type of summary
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum SummaryType {
    AutoGenerated,
    UserProvided,
    SystemProvided,
}

/// Reference to a memory entry
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct MemoryRef {
    pub memory_id: String,
    pub memory_hash: ContentHash,
    pub memory_type: MemoryType,
}

/// Type of memory
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum MemoryType {
    LongTerm,
    ShortTerm,
    Ephemeral,
}

/// Reference to rules
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RuleRef {
    pub rule_set_id: String,
    pub rules_hash: ContentHash,
}

/// Model configuration at turn creation
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ModelConfig {
    pub provider: String,
    pub model: String,
    pub temperature: Option<f32>,
    pub top_p: Option<f32>,
    pub max_tokens: Option<u32>,
    pub stop_sequences: Vec<String>,
    pub feature_flags: HashMap<String, bool>,
}

impl Default for ModelConfig {
    fn default() -> Self {
        Self {
            provider: "unknown".to_string(),
            model: "unknown".to_string(),
            temperature: None,
            top_p: None,
            max_tokens: None,
            stop_sequences: Vec::new(),
            feature_flags: HashMap::new(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_context_snapshot_creation() {
        let turn_id = TurnId::new();
        let ctx = ContextSnapshot::new(turn_id);
        assert_eq!(ctx.turn_id, turn_id);
        assert!(ctx.selected_files.is_empty());
    }

    #[test]
    fn test_context_snapshot_add_file() {
        let mut ctx = ContextSnapshot::new(TurnId::new());
        ctx.add_selected_file(SelectedFileRef {
            path: "foo.rs".to_string(),
            blob_hash: ContentHash::new(b"fn main() {}"),
            line_range: Some(LineRange { start: 1, end: 10 }),
            relevance_score: Some(0.9),
        });
        assert_eq!(ctx.selected_files.len(), 1);
        assert_eq!(ctx.total_references(), 1);
    }

    #[test]
    fn test_model_config_default() {
        let config = ModelConfig::default();
        assert_eq!(config.provider, "unknown");
        assert!(config.temperature.is_none());
    }
}
